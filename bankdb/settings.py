# ── Database configuration ──────────────────────────────────────────
# When DUMMY_DATABASE=true  →  local SQLite (no external dependency)
# When DUMMY_DATABASE=false →  MySQL via environment variables
USE_DUMMY_DB = os.getenv("DUMMY_DATABASE", "false").lower() == "true"

if USE_DUMMY_DB:
    DATABASES = {
        "default": {
            "ENGINE": "django.db.backends.sqlite3",
            "NAME": BASE_DIR / "db.sqlite3",
        }
    }
else:
    DB_NAME = os.getenv("DB_NAME", "bank_db")
    DB_USER = os.getenv("DB_USER", "root")
    DB_PASSWORD = os.getenv("DB_PASSWORD", "")
    DB_HOST = os.getenv("DB_HOST", "localhost")
    DB_PORT = int(os.getenv("DB_PORT", "3306"))
    _db_options = {"ssl": {"ssl": {}}} if os.getenv("DB_SSL", "true").lower() == "true" else {}
    DATABASES = {
        "default": {
            "ENGINE": "django.db.backends.mysql",
            "NAME": DB_NAME,
            "USER": DB_USER,
            "PASSWORD": DB_PASSWORD,
            "HOST": DB_HOST,
            "PORT": DB_PORT,
            "OPTIONS": _db_options,
        }
    }

